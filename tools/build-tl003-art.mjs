// Builds the TL003 pixel art with pxl and copies the sprite sheet into the game.
//   art/tl003/tl003.px.js  ->  TL003/public/assets/pixel/tl003.png
//                           ->  src/tl003/generated/sprites.ts (frame rectangles + animation timings)
// Usage: npm run art:tl003            (previews stay in art/tl003/out, which is git-ignored)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadProject, writeOutputs } from 'pxl-pixelart';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'art/tl003/tl003.px.js'), out = join(root, 'art/tl003/out');
const project = loadProject(source);
const result = writeOutputs(project, out, { preview: !process.argv.includes('--no-preview') });
for (const error of result.errors) console.error('error: ' + error.message);
if (result.errors.length) process.exit(1);

const sheet = JSON.parse(readFileSync(join(out, 'tl003.json'), 'utf8'));
const names = Object.keys(sheet.frames);
const frames = Object.fromEntries(names.map(name => { const f = sheet.frames[name].frame; return [name, [f.x, f.y, f.w, f.h]]; }));
const anims = Object.fromEntries(sheet.meta.frameTags.map(tag => {
  const list = names.slice(tag.from, tag.to + 1);
  return [tag.name, { frames: list, ms: list.map(n => sheet.frames[n].duration ?? 100) }];
}));

mkdirSync(join(root, 'TL003/public/assets/pixel'), { recursive: true });
copyFileSync(join(out, 'tl003.png'), join(root, 'TL003/public/assets/pixel/tl003.png'));
mkdirSync(join(root, 'src/tl003/generated'), { recursive: true });
writeFileSync(join(root, 'src/tl003/generated/sprites.ts'), `// Generated by tools/build-tl003-art.mjs from art/tl003/tl003.px.js. Do not edit.
export const SHEET_SIZE = ${JSON.stringify(sheet.meta.size)} as const;
export const FRAMES: Record<string, readonly [number, number, number, number]> = ${JSON.stringify(frames)};
export const ANIMS: Record<string, { frames: readonly string[]; ms: readonly number[] }> = ${JSON.stringify(anims)};
`);
console.log(`TL003 art: ${names.length} frames, ${Object.keys(anims).length} animations, sheet ${sheet.meta.size.w}x${sheet.meta.size.h}`);
